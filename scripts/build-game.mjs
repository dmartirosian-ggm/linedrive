// Bundles game/index.html into a single offline HTML string for the app.
// Inlines three.js (pinned 0.147.0), fonts and textures, so the game needs no network.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let html = readFileSync(path.join(root, 'game/index.html'), 'utf8');

html = html.replace(/<!--INLINE:([^>]+?)-->/g, (_, spec) => {
  const [pkg, ...rest] = spec.trim().split('/');
  const file = path.join(root, 'node_modules', pkg, ...rest);
  const code = readFileSync(file, 'utf8').replace(/<\/script/gi, '<\\/script');
  return `<script>${code}</script>`;
});

const font = (pkg, file, family, weight) => {
  const p = path.join(root, 'node_modules', pkg, 'files', file);
  const b64 = readFileSync(p).toString('base64');
  return `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
};
const faces = [
  font('@fontsource/monoton', 'monoton-latin-400-normal.woff2', 'Monoton', 400),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-400-normal.woff2', 'Chakra Petch', 400),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-600-normal.woff2', 'Chakra Petch', 600),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-700-normal.woff2', 'Chakra Petch', 700),
].join('\n');
html = html.replace('/*FONTS*/', faces);

// Music: the song catalogue (game/music/tracks.json) is embedded in the game; the encoded
// songs in assets/music (made by scripts/encode-music.mjs) ship as native app assets and are
// handed to the game one at a time, so they are not inlined here.
const tracks = JSON.parse(readFileSync(path.join(root, 'game/music/tracks.json'), 'utf8'));
for (const t of tracks) {
  if (!existsSync(path.join(root, 'assets/music', t.id + '.mp3')))
    throw new Error(`assets/music/${t.id}.mp3 is missing. Run: node scripts/encode-music.mjs`);
}
const catalogue = tracks.map(({ src, ...t }) => t);
// Embed the box textures and sky silhouettes in game/tex as data URLs.
const texDir = path.join(root, 'game/tex');
const texs = {};
for (const f of readdirSync(texDir).filter((f) => /\.(png|jpg)$/.test(f)).sort()) {
  const mime = f.endsWith('.png') ? 'image/png' : 'image/jpeg';
  texs[f.replace(/\.(png|jpg)$/, '')] = `data:${mime};base64,` + readFileSync(path.join(texDir, f)).toString('base64');
}
const musicScript = `<script>window.__LD_TRACKS=${JSON.stringify(catalogue)};window.__LD_TEX=${JSON.stringify(texs)};</script>`;

if (/<!--INLINE:|\/\*FONTS\*\//.test(html)) throw new Error('Unresolved placeholder in game HTML');
const [before, after, extra] = html.split('<!--MUSIC-->');
if (after === undefined || extra !== undefined) throw new Error('Expected exactly one <!--MUSIC--> placeholder');

mkdirSync(path.join(root, 'dist'), { recursive: true });
const full = before + musicScript + after;
writeFileSync(path.join(root, 'dist/game.html'), full);
// The texture data URLs are kept in their own ASCII-only literal: Hermes stores any string with a
// non-ASCII character at two bytes per char, which would double the app's size.
writeFileSync(
  path.join(root, 'src/gameHtml.ts'),
  `// Generated by scripts/build-game.mjs from game/index.html and game/music. Do not edit by hand.\n` +
    `const BEFORE: string = ${JSON.stringify(before)};\n` +
    `const MUSIC: string = ${JSON.stringify(musicScript)};\n` +
    `const AFTER: string = ${JSON.stringify(after)};\n` +
    `export const GAME_HTML: string = [BEFORE, MUSIC, AFTER].join('');\n`
);
writeFileSync(
  path.join(root, 'src/musicAssets.ts'),
  `// Generated by scripts/build-game.mjs from game/music/tracks.json. Do not edit by hand.\n` +
    `export const MUSIC: Record<string, number> = {\n` +
    tracks.map((t) => `  ${JSON.stringify(t.id)}: require('../assets/music/${t.id}.mp3'),\n`).join('') +
    `};\n`
);
console.log(`game bundled: ${(full.length / 1024).toFixed(0)} KB (${tracks.length} songs as app assets, textures ${(musicScript.length / 1024).toFixed(0)} KB)`);
