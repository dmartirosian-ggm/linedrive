// Bundles game/index.html into a single offline HTML string for the app.
// Inlines three.js (pinned 0.147.0) and the two fonts, so the game needs no network.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let html = readFileSync(path.join(root, 'game/index.html'), 'utf8');

html = html.replace(/<!--INLINE:([^>]+?)-->/g, (_, spec) => {
  const [pkg, ...rest] = spec.trim().split('/');
  const file = path.join(root, 'node_modules', pkg, ...rest);
  const code = readFileSync(file, 'utf8').replace(/<\/script/gi, '<\\/script');
  return `<script>${code}</script>`;
});

const font = (pkg, file, family, weight) => {
  const p = path.join(root, 'node_modules', pkg, 'files', file);
  const b64 = readFileSync(p).toString('base64');
  return `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
};
const faces = [
  font('@fontsource/monoton', 'monoton-latin-400-normal.woff2', 'Monoton', 400),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-400-normal.woff2', 'Chakra Petch', 400),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-600-normal.woff2', 'Chakra Petch', 600),
  font('@fontsource/chakra-petch', 'chakra-petch-latin-700-normal.woff2', 'Chakra Petch', 700),
].join('\n');
html = html.replace('/*FONTS*/', faces);

// Embed every track in game/music so the game plays offline inside the app.
const musicDir = path.join(root, 'game/music');
const music = {};
for (const f of readdirSync(musicDir).filter((f) => f.endsWith('.mp3')).sort()) {
  music[f] = readFileSync(path.join(musicDir, f)).toString('base64');
}
const musicScript = `<script>window.__LD_MUSIC=${JSON.stringify(music)};</script>`;

if (/<!--INLINE:|\/\*FONTS\*\//.test(html)) throw new Error('Unresolved placeholder in game HTML');
const [before, after, extra] = html.split('<!--MUSIC-->');
if (after === undefined || extra !== undefined) throw new Error('Expected exactly one <!--MUSIC--> placeholder');

mkdirSync(path.join(root, 'dist'), { recursive: true });
const full = before + musicScript + after;
writeFileSync(path.join(root, 'dist/game.html'), full);
// The music is kept in its own ASCII-only literal: Hermes stores any string with a
// non-ASCII character at two bytes per char, which would double the app's size.
writeFileSync(
  path.join(root, 'src/gameHtml.ts'),
  `// Generated by scripts/build-game.mjs from game/index.html and game/music. Do not edit by hand.\n` +
    `const BEFORE: string = ${JSON.stringify(before)};\n` +
    `const MUSIC: string = ${JSON.stringify(musicScript)};\n` +
    `const AFTER: string = ${JSON.stringify(after)};\n` +
    `export const GAME_HTML: string = [BEFORE, MUSIC, AFTER].join('');\n`
);
console.log(`game bundled: ${(full.length / 1024).toFixed(0)} KB (music ${(musicScript.length / 1024).toFixed(0)} KB)`);
